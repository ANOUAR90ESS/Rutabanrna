const DICTS: Record<Language, UiStrings> = { es, en, ca, ar };

export function ui(lang: Language): UiStrings {
  return DICTS[lang] || es;
}

export function fmt(s: string, ...args: (string | number)[]): string {
  return args.reduce<string>((acc, v, i) => acc.replace(`{${i}}`, String(v)), s);
}
